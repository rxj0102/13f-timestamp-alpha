"""Does the day a hedge fund files its 13F tell you anything? Measure it and render the README.

Inputs : results/filing_history.csv        every original 13F-HR of the universe managers
                                           (from scripts/build_manager_universe.py)
         data/reference/manager_universe.csv
         data/reference/ctr_log.csv        positions first disclosed in NEW HOLDINGS amendments
                                           (from scripts/build_ctr_log.py)
         SEC full-index form.idx, 2024 Q1  every 13F-HR filed that quarter, for the wider population.
                                           Read from data/raw/edgar_cache when present; otherwise the
                                           population figures are carried over from the last run that
                                           had it, and the summary records the date of that run.
Outputs: results/filing_timing_summary.json and the README blocks between the generated markers

    python scripts/filing_timing_study.py           # compute and rewrite the README blocks
    python scripts/filing_timing_study.py --check   # exit 1 if the README is out of date with results/
"""
from __future__ import annotations

import json
import os
import re
import sys
import urllib.request
from pathlib import Path

import numpy as np
import pandas as pd
from pandas.tseries.holiday import USFederalHolidayCalendar
from pandas.tseries.offsets import CustomBusinessDay

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / "results"
MARK = "<!-- {name}:start (generated by scripts/filing_timing_study.py, do not edit by hand) -->"
END = "<!-- {name}:end -->"
POPULATION_MEASURED = "2026-11-10"   # date the 2024 Q1 index was last read (commit 27d39b9)
BD = CustomBusinessDay(calendar=USFederalHolidayCalendar())


def business_days_before_deadline(report_date: pd.Timestamp, filing_date: pd.Timestamp) -> int:
    raw = report_date + pd.Timedelta(days=45)
    eff = raw if BD.is_on_offset(raw) else raw + BD
    if filing_date > eff:
        return -1
    return len(pd.bdate_range(filing_date, eff, freq=BD)) - 1


def population(ua: str) -> dict:
    cache = ROOT / "data" / "raw" / "edgar_cache" / "full_index_2024_QTR1_form.idx"
    if not cache.exists() and not ua:
        previous = json.loads((RES / "filing_timing_summary.json").read_text())["population_2023q4"]
        return {**previous, "measured": previous.get("measured", POPULATION_MEASURED)}
    if not cache.exists():
        cache.parent.mkdir(parents=True, exist_ok=True)
        req = urllib.request.Request("https://www.sec.gov/Archives/edgar/full-index/2024/QTR1/form.idx", headers={"User-Agent": ua})
        cache.write_bytes(urllib.request.urlopen(req, timeout=120).read())
    days = []
    for line in cache.read_text(errors="replace").splitlines():
        if line.startswith("13F-HR "):
            d = pd.Timestamp(re.search(r"(\d{4}-\d{2}-\d{2})", line).group(1))
            days.append((d - pd.Timestamp("2023-12-31")).days)
    d = pd.Series(days)
    return {"n_filings": int(len(d)), "median_day": float(d.median()),
            "share_by_day_15": float((d <= 15).mean()), "share_by_day_30": float((d <= 30).mean()),
            "share_day_40_plus": float((d >= 40).mean()), "measured": str(pd.Timestamp.today().date())}


def confidential(ctr: pd.DataFrame) -> dict:
    """What the NEW HOLDINGS amendments contain, and how many are confirmed confidential treatment."""
    by_mgr = ctr.groupby("manager_name").size().sort_values(ascending=False)
    per = ctr.groupby(["manager_name", "accession"]).size()
    big = per[per >= 100]
    conf = ctr[ctr.conf_denied_expired]
    lag = ctr.disclosure_lag_quarters
    return {"n_rows": int(len(ctr)), "n_managers": int(ctr.cik.nunique()), "n_amendments": int(ctr.accession.nunique()),
            "top2_managers": list(by_mgr.index[:2]), "top2_share": float(by_mgr.iloc[:2].sum() / len(ctr)),
            "n_confirmed": int(len(conf)), "confirmed_managers": int(conf.cik.nunique()),
            "confirmed_share": float(len(conf) / len(ctr)),
            "confirmed_years": f"{conf.quarter_label.str[-4:].min()} to {conf.quarter_label.str[-4:].max()}",
            "n_large_amendments": int(len(big)), "large_amendment_share": float(big.sum() / len(ctr)),
            "median_rows_other_amendments": float(per[per < 100].median()),
            "median_lag_quarters": float(lag.median()), "share_lag_over_4": float((lag > 4).mean()),
            "confirmed_median_lag_quarters": float(conf.disclosure_lag_quarters.median())}


def compute() -> dict:
    sys.path.insert(0, str(ROOT))
    import config

    h = pd.read_csv(RES / "filing_history.csv", parse_dates=["report_date", "filing_date"])
    h["bdays_before_deadline"] = [business_days_before_deadline(r, f) for r, f in zip(h.report_date, h.filing_date)]
    u = pd.read_csv(ROOT / "data" / "reference" / "manager_universe.csv", comment="#")
    d, b = h.days_after_quarter_end, h.bdays_before_deadline
    within = h.groupby("cik").days_after_quarter_end.std()
    med = h.groupby("manager_name").days_after_quarter_end.median()
    inc = h[h.cik.isin(u[u.include_flag].cik)]
    early_cut = config.URGENCY_EARLY_THRESHOLD * config.FILING_DEADLINE_DAYS
    out = {
        "period": f"{h.report_date.min().date()} to {h.report_date.max().date()}",
        "n_managers": int(h.cik.nunique()), "n_filings": int(len(h)),
        "median_day": float(d.median()), "std_day": float(d.std()),
        "median_within_manager_std": float(within.median()),
        "share_on_deadline": float((b == 0).mean()), "share_one_bday_before": float((b == 1).mean()),
        "share_2_to_5_bdays_before": float(((b >= 2) & (b <= 5)).mean()), "share_over_5_bdays_before": float((b > 5).mean()),
        "share_after_deadline": float((b < 0).mean()),
        "n_early_bucket": int((d <= early_cut).sum()), "early_cut_day": float(early_cut),
        "managers_median_below_40": int((med < 40).sum()),
        "blackrock_median_day": float(med.get("Blackrock Inc", np.nan)), "vanguard_median_day": float(med.get("Vanguard Group", np.nan)),
        "n_included": int(u.include_flag.sum()), "included_filings": int(len(inc)),
        "included_share_on_deadline_or_1_before": float((inc.bdays_before_deadline.between(0, 1)).mean()),
        "population_2023q4": population(os.getenv("EDGAR_USER_AGENT", config.EDGAR_USER_AGENT)),
        "confidential": confidential(pd.read_csv(ROOT / "data" / "reference" / "ctr_log.csv", comment="#")),
    }
    out = json.loads(json.dumps(out), parse_float=lambda x: float(f"{float(x):.6g}"))
    RES.mkdir(exist_ok=True)
    (RES / "filing_timing_summary.json").write_text(json.dumps(out, indent=2))
    return out


def pct(x: float) -> str:
    return f"{x * 100:.1f}%"


def headline(s: dict) -> str:
    p, c = s["population_2023q4"], s["confidential"]
    on_or_one = s["share_on_deadline"] + s["share_one_bday_before"]
    checks = {
        "more than 90% of filings are on the deadline or one business day before": on_or_one > 0.9,
        "almost no filing falls in the early bucket": s["n_early_bucket"] <= 5,
        "no manager's median filing day is below 40": s["managers_median_below_40"] == 0,
        "the managers the strategy would trade are no different": s["included_share_on_deadline_or_1_before"] > 0.9,
        "the wider population does vary": p["share_by_day_30"] > 0.2,
        "few amendment rows are confirmed confidential treatment": c["confirmed_share"] < 0.05,
        "two managers account for most amendment rows": c["top2_share"] > 0.8,
        "most amendment rows sit in a handful of amendments with 100 or more positions":
            c["large_amendment_share"] > 0.8 and c["n_large_amendments"] <= 12,
    }
    failed = [k for k, ok in checks.items() if not ok]
    if failed:
        sys.exit("README summary no longer matches the results; rewrite headline() in "
                 "scripts/filing_timing_study.py. Failed: " + "; ".join(failed))
    return (
        f"**Answer, from {s['n_filings']:,} filings by {s['n_managers']} managers over {s['period'][:4]} to "
        f"{s['period'][-10:-6]}: no, because hedge funds all file on the same day.** {pct(on_or_one)} of filings "
        f"land on the deadline or one business day before it, the typical manager's filing day varies by "
        f"{s['median_within_manager_std']:.1f} days from quarter to quarter, and in ten years only "
        f"{s['n_early_bucket']} filing falls in the early bucket the strategy needed for its comparison. "
        f"Filing day is a constant set by the calendar, so it cannot carry information about conviction. "
        f"Timing does vary across all 13F filers ({pct(p['share_by_day_30'])} file within 30 days), which is "
        f"where any test would have to look. The confidential treatment data that was meant to correct "
        f"the signal was mostly something else: of {c['n_rows']:,} positions first disclosed in amendments, "
        f"{c['n_confirmed']} come from filings that say they respond to a confidential treatment request, and "
        f"{pct(c['top2_share'])} come from two managers."
    )


def results(s: dict) -> str:
    p, c = s["population_2023q4"], s["confidential"]
    return "\n".join([
        f"Measured from SEC EDGAR for the {s['n_managers']} managers in `data/reference/manager_universe.csv`, "
        f"{s['n_filings']:,} original 13F-HR filings for report periods {s['period']}.",
        "",
        "### When hedge funds file",
        "",
        "| Statistic | Value |",
        "|---|---|",
        f"| Median filing day after quarter end | {s['median_day']:.0f} |",
        f"| Standard deviation of filing day | {s['std_day']:.1f} days |",
        f"| Median within-manager standard deviation | {s['median_within_manager_std']:.1f} days |",
        f"| Filed on the effective deadline (day 45, or the next business day) | {pct(s['share_on_deadline'])} |",
        f"| Filed one business day before the deadline | {pct(s['share_one_bday_before'])} |",
        f"| Filed 2 to 5 business days before | {pct(s['share_2_to_5_bdays_before'])} |",
        f"| Filed more than 5 business days before | {pct(s['share_over_5_bdays_before'])} |",
        f"| Filed after the deadline | {pct(s['share_after_deadline'])} |",
        f"| Filings in the strategy's EARLY bucket (day {s['early_cut_day']:.0f} or earlier) | {s['n_early_bucket']} |",
        f"| Managers whose median filing day is below 40 | {s['managers_median_below_40']} |",
        f"| The {s['n_included']} managers that pass the strategy's screen: on the deadline or one day before | "
        f"{pct(s['included_share_on_deadline_or_1_before'])} of {s['included_filings']} filings |",
        f"| BlackRock and Vanguard, meant as early filing controls: median day | {s['blackrock_median_day']:.0f} and "
        f"{s['vanguard_median_day']:.0f} |",
        "",
        "### When everyone else files",
        "",
        f"All {p['n_filings']:,} 13F-HR filed in the first quarter of 2024, mostly for the period ending 2023-12-31: "
        f"median day {p['median_day']:.0f}, {pct(p['share_by_day_15'])} by day 15, {pct(p['share_by_day_30'])} by "
        f"day 30, {pct(p['share_day_40_plus'])} on day 40 or later. Read from the SEC full index on {p['measured']}.",
        "",
        "### What the amendments contain",
        "",
        "| Statistic | Value |",
        "|---|---|",
        f"| Positions first disclosed in NEW HOLDINGS amendments | {c['n_rows']:,} in {c['n_amendments']} amendments "
        f"from {c['n_managers']} managers |",
        f"| From {c['top2_managers'][0]} and {c['top2_managers'][1]} | {pct(c['top2_share'])} |",
        f"| From filings stating they respond to a denied or expired confidential treatment request | "
        f"{c['n_confirmed']} ({pct(c['confirmed_share'])}), from {c['confirmed_managers']} managers, "
        f"{c['confirmed_years']} |",
        f"| In amendments that add 100 or more positions at once | {pct(c['large_amendment_share'])}, from "
        f"{c['n_large_amendments']} amendments |",
        f"| Median positions per amendment, all others | {c['median_rows_other_amendments']:.0f} |",
        f"| Median delay from the report date to the amendment | {c['median_lag_quarters']:.0f} quarter |",
        f"| Delay of more than four quarters | {pct(c['share_lag_over_4'])} |",
        f"| Median delay for the confirmed confidential positions | {c['confirmed_median_lag_quarters']:.0f} quarter |",
    ])


def fill(text: str, name: str, body: str) -> str:
    start, end = MARK.format(name=name), END.format(name=name)
    a, b = text.index(start) + len(start), text.index(end)
    return text[:a] + "\n" + body + "\n" + text[b:]


def main() -> None:
    readme = ROOT / "README.md"
    text = readme.read_text()
    s = json.loads((RES / "filing_timing_summary.json").read_text()) if "--check" in sys.argv else compute()
    new = fill(fill(text, "headline", headline(s)), "results", results(s))
    if "--check" in sys.argv:
        if new != text:
            sys.exit("README.md is out of date. Run: python scripts/filing_timing_study.py")
        print("README.md matches results/")
        return
    readme.write_text(new)
    print(json.dumps(s, indent=2))


if __name__ == "__main__":
    main()
