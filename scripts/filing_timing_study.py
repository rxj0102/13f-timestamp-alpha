"""Measure how much 13F filing timing actually varies, and render the README Key Findings.

Inputs : results/filing_history.csv            (from scripts/build_manager_universe.py)
         data/reference/manager_universe.csv
         SEC full-index form.idx for 2024 Q1     (all 13F-HR filed for period 2023-12-31)
Outputs: results/filing_timing_summary.json
         README.md Key Findings block (between the results markers)

    python scripts/filing_timing_study.py           # compute and rewrite README block
    python scripts/filing_timing_study.py --check   # exit 1 if README is out of date with results/
"""
from __future__ import annotations

import json
import os
import re
import sys
import urllib.request
from pathlib import Path

import numpy as np
import pandas as pd
from pandas.tseries.holiday import USFederalHolidayCalendar
from pandas.tseries.offsets import CustomBusinessDay

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / "results"
START = "<!-- results:start (generated by scripts/filing_timing_study.py, do not edit by hand) -->"
END = "<!-- results:end -->"
BD = CustomBusinessDay(calendar=USFederalHolidayCalendar())


def business_days_before_deadline(report_date: pd.Timestamp, filing_date: pd.Timestamp) -> int:
    raw = report_date + pd.Timedelta(days=45)
    eff = raw if BD.is_on_offset(raw) else raw + BD
    if filing_date > eff:
        return -1
    return len(pd.bdate_range(filing_date, eff, freq=BD)) - 1


def population(ua: str) -> dict:
    cache = ROOT / "data" / "raw" / "edgar_cache" / "full_index_2024_QTR1_form.idx"
    if not cache.exists():
        cache.parent.mkdir(parents=True, exist_ok=True)
        req = urllib.request.Request("https://www.sec.gov/Archives/edgar/full-index/2024/QTR1/form.idx", headers={"User-Agent": ua})
        cache.write_bytes(urllib.request.urlopen(req, timeout=120).read())
    days = []
    for line in cache.read_text(errors="replace").splitlines():
        if line.startswith("13F-HR "):
            d = pd.Timestamp(re.search(r"(\d{4}-\d{2}-\d{2})", line).group(1))
            days.append((d - pd.Timestamp("2023-12-31")).days)
    d = pd.Series(days)
    return {"n_filings": int(len(d)), "median_day": float(d.median()),
            "share_by_day_15": float((d <= 15).mean()), "share_by_day_30": float((d <= 30).mean()),
            "share_day_40_plus": float((d >= 40).mean())}


def compute() -> dict:
    sys.path.insert(0, str(ROOT))
    import config

    h = pd.read_csv(RES / "filing_history.csv", parse_dates=["report_date", "filing_date"])
    h["bdays_before_deadline"] = [business_days_before_deadline(r, f) for r, f in zip(h.report_date, h.filing_date)]
    u = pd.read_csv(ROOT / "data" / "reference" / "manager_universe.csv", comment="#")
    d, b = h.days_after_quarter_end, h.bdays_before_deadline
    within = h.groupby("cik").days_after_quarter_end.std()
    med = h.groupby("manager_name").days_after_quarter_end.median()
    inc = h[h.cik.isin(u[u.include_flag].cik)]
    early_cut = config.URGENCY_EARLY_THRESHOLD * config.FILING_DEADLINE_DAYS
    out = {
        "period": f"{h.report_date.min().date()} to {h.report_date.max().date()}",
        "n_managers": int(h.cik.nunique()), "n_filings": int(len(h)),
        "median_day": float(d.median()), "std_day": float(d.std()),
        "median_within_manager_std": float(within.median()),
        "share_on_deadline": float((b == 0).mean()), "share_one_bday_before": float((b == 1).mean()),
        "share_2_to_5_bdays_before": float(((b >= 2) & (b <= 5)).mean()), "share_over_5_bdays_before": float((b > 5).mean()),
        "share_after_deadline": float((b < 0).mean()),
        "n_early_bucket": int((d <= early_cut).sum()), "early_cut_day": float(early_cut),
        "managers_median_below_40": int((med < 40).sum()),
        "blackrock_median_day": float(med.get("Blackrock Inc", np.nan)), "vanguard_median_day": float(med.get("Vanguard Group", np.nan)),
        "n_included": int(u.include_flag.sum()), "included_filings": int(len(inc)),
        "included_share_on_deadline_or_1_before": float((inc.bdays_before_deadline.between(0, 1)).mean()),
        "population_2023q4": population(os.getenv("EDGAR_USER_AGENT", config.EDGAR_USER_AGENT)),
    }
    RES.mkdir(exist_ok=True)
    (RES / "filing_timing_summary.json").write_text(json.dumps(out, indent=2))
    return out


def pct(x: float) -> str:
    return f"{x * 100:.1f}%"


def render(s: dict) -> str:
    p = s["population_2023q4"]
    return "\n".join([
        f"Measured from SEC EDGAR for the {s['n_managers']} managers in `data/reference/manager_universe.csv`, "
        f"{s['n_filings']} original 13F-HR filings for report periods {s['period']}.",
        "",
        "| Statistic | Value |",
        "|---|---|",
        f"| Median filing day after quarter end | {s['median_day']:.0f} |",
        f"| Standard deviation of filing day | {s['std_day']:.1f} days |",
        f"| Median within-manager standard deviation | {s['median_within_manager_std']:.1f} days |",
        f"| Filed on the effective deadline (day 45, or the next business day) | {pct(s['share_on_deadline'])} |",
        f"| Filed one business day before the deadline | {pct(s['share_one_bday_before'])} |",
        f"| Filed 2 to 5 business days before | {pct(s['share_2_to_5_bdays_before'])} |",
        f"| Filed more than 5 business days before | {pct(s['share_over_5_bdays_before'])} |",
        f"| Filings in the EARLY bucket (day {s['early_cut_day']:.0f} or earlier) | {s['n_early_bucket']} |",
        f"| Managers whose median filing day is below 40 | {s['managers_median_below_40']} |",
        "",
        "| Finding | Evidence |",
        "|---|---|",
        f"| Filing timing barely varies in this universe | {pct(s['share_on_deadline'] + s['share_one_bday_before'])} of filings land on the deadline or one business day before it |",
        f"| The late versus early comparison cannot be run | Only {s['n_early_bucket']} filing{'s fall' if s['n_early_bucket'] != 1 else ' falls'} in the EARLY bucket across the whole sample |",
        f"| The index-fund negative control does not hold | BlackRock median day {s['blackrock_median_day']:.0f}, Vanguard median day {s['vanguard_median_day']:.0f}; both file late, not early |",
        f"| The {s['n_included']} managers that pass the config filters are no different | {pct(s['included_share_on_deadline_or_1_before'])} of their {s['included_filings']} filings are on the deadline or one business day before |",
        f"| Timing does vary in the full 13F population | All {p['n_filings']:,} 13F-HR filed in 2024 Q1 (mostly period 2023-12-31): median day {p['median_day']:.0f}, {pct(p['share_by_day_30'])} filed by day 30, {pct(p['share_by_day_15'])} by day 15 |",
        "",
        "Implication: within the hedge-fund universe this strategy targets, filing day is close to a constant set by the deadline and the calendar, so `filing_urgency` carries almost no cross-sectional or within-manager information. No return backtest is reported, because there is no timing variation to test. Variation exists in the wider 13F population, but there filing day mostly separates manager types (banks and advisers file early, hedge funds file at the deadline), which confounds any conviction reading.",
    ])


def main() -> None:
    readme = ROOT / "README.md"
    text = readme.read_text()
    pre, rest = text.split(START, 1)
    _, post = rest.split(END, 1)
    if "--check" in sys.argv:
        s = json.loads((RES / "filing_timing_summary.json").read_text())
        if pre + START + "\n" + render(s) + "\n" + END + post != text:
            sys.exit("README.md Key Findings are out of date. Run: python scripts/filing_timing_study.py")
        print("README.md Key Findings match results/")
        return
    s = compute()
    readme.write_text(pre + START + "\n" + render(s) + "\n" + END + post)
    print(json.dumps(s, indent=2))


if __name__ == "__main__":
    main()
