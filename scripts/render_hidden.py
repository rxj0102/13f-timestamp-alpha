"""Render the hidden-positions part of the README from results/hidden_summary.json.

    python scripts/render_hidden.py          rewrite the generated blocks
    python scripts/render_hidden.py --check  exit 1 if the README is out of date
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MARK = "<!-- {name}:start (generated by scripts/render_hidden.py, do not edit by hand) -->"
END = "<!-- {name}:end -->"
ROWS = [("report|1", "1 quarter from the report date"), ("report|2", "2 quarters from the report date (primary)"),
        ("report|4", "4 quarters from the report date"), ("reveal|1", "1 quarter from the reveal"),
        ("reveal|2", "2 quarters from the reveal"), ("reveal|4", "4 quarters from the reveal")]


def headline(m: dict) -> str:
    r, s, x = m["results"], m["sample"], m["split_excluded"]
    p, y4, rv = r["report|2"], r["report|4"], r["reveal|2"]
    checks = {
        "the primary difference is not significant": abs(p["diff_ew"]["t"]) < 1.96,
        "over four quarters hidden trail shown, but not significantly": y4["diff_ew"]["mean"] < 0 and abs(y4["diff_ew"]["t"]) < 1.96,
        "value weighted, the four quarter gap is not significant": abs(y4["diff_vw"]["t"]) < 1.96,
        "nothing tradable after the reveal": all(abs(r[k]["diff_ew"]["t"]) < 1.96 for k in ("reveal|1", "reveal|2")),
        "the median pair has hidden behind at every horizon": all(v["diff_ew"]["median_pair"] < 0 for v in r.values()),
        "the split check never favours hidden": all(v["diff_ew"]["mean"] < 0 for v in x.values()),
        "the split check is significant at the primary horizon": x["report|2"]["diff_ew"]["t"] < -1.96,
        "almost every hidden position is priced": s["share_hidden_priced"] > 0.99,
    }
    failed = [k for k, ok in checks.items() if not ok]
    if failed:
        raise SystemExit("README summary no longer matches the results; rewrite headline() in "
                         "scripts/render_hidden.py. Failed: " + "; ".join(failed))
    return (
        f"**Answer, from {s['manager_quarters']} manager-quarters by {s['managers']} managers, {s['first_period'][:4]} "
        f"to {s['last_period'][:4]}: no.** Over the two quarters after the report date, about the time a position "
        f"stays hidden, the positions a manager hid returned {p['hidden_ew']['mean']:.1%} on average against "
        f"{p['shown_ew']['mean']:.1%} for the positions it showed, a difference of {p['diff_ew']['mean']:+.1%} "
        f"(t = {p['diff_ew']['t']:.2f}). In the typical manager-quarter the hidden positions do worse "
        f"(median {p['diff_ew']['median_pair']:+.1%}), and over four quarters they trail by "
        f"{abs(y4['diff_ew']['mean']):.1%}, but the four quarter windows overlap from one quarter to the next and once that "
        f"is allowed for the gap is not significant (t = {y4['diff_ew']['t']:.2f}). "
        f"After the reveal there is nothing to trade: over the next two quarters the difference is "
        f"{rv['diff_ew']['mean']:+.1%} (t = {rv['diff_ew']['t']:.2f})."
    )


def results(m: dict) -> str:
    r, s, x = m["results"], m["sample"], m["split_excluded"]
    out = [f"{s['amendments']:,} amendments revealing {s['hidden_positions']:,} hidden positions, paired with "
           f"{s['shown_positions']:,} positions shown in the same managers' original filings. Report periods "
           f"{s['first_period']} to {s['last_period']}. The median manager-quarter reveals "
           f"{r['report|2']['median_hidden_positions']:.0f} hidden positions against "
           f"{r['report|2']['median_shown_positions']:.0f} shown, and the median amendment is filed "
           f"{s['median_days_to_reveal']:.0f} days after quarter end. Returns are quarter-end price changes "
           f"without dividends; cells average across managers within a quarter, then across quarters, with "
           f"the t-statistic across quarters. Windows of k quarters overlap from one report quarter to the next, "
           f"so their t-statistics use Newey-West errors with k - 1 lags.", "",
           "| Window | Quarters | Pairs | Hidden | Shown | Difference | t | Median pair | Value weighted | t |",
           "|---|---|---|---|---|---|---|---|---|---|"]
    for k, name in ROWS:
        v = r[k]
        d, w = v["diff_ew"], v["diff_vw"]
        out.append(f"| {name} | {d['quarters']} | {d['pairs']} | {v['hidden_ew']['mean']:+.1%} | {v['shown_ew']['mean']:+.1%} | "
                   f"{d['mean']:+.1%} | {d['t']:+.2f} | {d['median_pair']:+.1%} | {w['mean']:+.1%} | {w['t']:+.2f} |")
    out += ["", "**Check: dropping securities with a suspected split instead of adjusting for it**", "",
            "| Window | Difference | t |", "|---|---|---|"]
    for k, name in ROWS:
        out.append(f"| {name} | {x[k]['diff_ew']['mean']:+.1%} | {x[k]['diff_ew']['t']:+.2f} |")
    out += ["", f"The six heaviest users of confidential treatment in the sample ({', '.join(s['top_managers'])}) "
            f"account for {s['top6_share_of_quarters']:.0%} of manager-quarters."]
    return "\n".join(out)


def fill(text: str, name: str, body: str) -> str:
    start, end = MARK.format(name=name), END.format(name=name)
    a, b = text.index(start) + len(start), text.index(end)
    return text[:a] + "\n" + body + "\n" + text[b:]


def main() -> None:
    m = json.loads((ROOT / "results" / "hidden_summary.json").read_text())
    readme = ROOT / "README.md"
    text = readme.read_text()
    new = fill(fill(text, "hidden-headline", headline(m)), "hidden-results", results(m))
    if "--check" in sys.argv:
        if new != text:
            print("README is out of date; run python scripts/render_hidden.py")
            sys.exit(1)
        print("README hidden-positions blocks match results/hidden_summary.json")
        return
    readme.write_text(new)
    print("README rendered")


if __name__ == "__main__":
    main()
